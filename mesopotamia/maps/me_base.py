def rough(poly, amp=0.16, step=0.28, f=None):
    """natural-looking border: every edge is resampled and pushed sideways by smooth noise (fixed by its coordinates)"""
    p = np.asarray(poly, float); out = []; f = f or 1.0 / (step * 2.6)
    for i in range(len(p)):
        a_, b_ = p[i], p[(i + 1) % len(p)]; d = b_ - a_; L = float(np.hypot(*d)); n = max(1, int(L / step)); nrm = np.array([-d[1], d[0]]) / max(L, 1e-9)
